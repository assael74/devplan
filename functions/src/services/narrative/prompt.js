function buildGenerateInput(input = {}) {
  return [
    BASE_INSTRUCTIONS,
    '',
    'משימה: צור Draft חדש של סיפור השחקן.',
    '',
    'NARRATIVE_INPUT:',
    JSON.stringify(input),
  ].join('\n')
}

function buildRefineInput({ input = {}, currentDraft = {}, instruction = '' } = {}) {
  return [
    BASE_INSTRUCTIONS,
    '',
    'משימה: חדד את ה-Draft הקיים לפי הוראת המשתמש, בלי לשנות את העובדות או את מסקנות המנוע.',
    '',
    'USER_INSTRUCTION:',
    String(instruction || '').trim(),
    '',
    'CURRENT_DRAFT:',
    JSON.stringify(currentDraft),
    '',
    'NARRATIVE_INPUT:',
    JSON.stringify(input),
  ].join('\n')
}

